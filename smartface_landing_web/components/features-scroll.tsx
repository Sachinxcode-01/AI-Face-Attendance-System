interface FeatureSection {
  id: string;
  icon: React.ReactNode;
  title: string;
  tag: string;
  description: string;
  bulletPoints: string[];
}

function ScrollTriggerText({
  section,
  index,
  setActiveIdx,
}: {
  section: FeatureSection;
  index: number;
  setActiveIdx: (idx: number) => void;
}) {
  const ref = useRef<HTMLDivElement>(null);
  const isInView = useInView(ref, {
    margin: '-30% 0px -40% 0px', // triggers when centered in viewport
  });

  useEffect(() => {
    if (isInView) {
      setActiveIdx(index);
    }
  }, [isInView, index, setActiveIdx]);

  return (
    <div
      ref={ref}
      className={`min-h-[70vh] flex flex-col justify-center py-12 border-l border-white/5 pl-8 md:pl-12 transition-opacity duration-500 ${
        isInView ? 'opacity-100' : 'opacity-30'
      }`}
    >
      <div className="flex items-center gap-2 text-xs font-mono text-primary uppercase mb-3">
        {section.icon}
        <span>{section.tag}</span>
      </div>
      <h3 className="text-2xl md:text-4xl font-extrabold text-white tracking-tight mb-4">
        {section.title}
      </h3>
      <p className="text-slate-400 text-sm md:text-base leading-relaxed mb-6">
        {section.description}
      </p>
      <ul className="flex flex-col gap-3 font-mono text-xs text-slate-300">
        {section.bulletPoints.map((bullet, idx) => (
          <li key={idx} className="flex items-center gap-2.5">
            <span className="w-1.5 h-1.5 rounded-full bg-primary" />
            <span>{bullet}</span>
          </li>
        ))}
      </ul>
    </div>
  );
}

